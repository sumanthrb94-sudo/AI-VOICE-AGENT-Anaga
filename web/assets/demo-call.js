  /* ---------------- call lifecycle ---------------- */
  function clock() {
    var s = Math.floor((Date.now() - t0) / 1000);
    $("timer").textContent = String(Math.floor(s / 60)).padStart(2, "0") + ":"
      + String(s % 60).padStart(2, "0");
  }

  function begin() {
    unlock();                                  // inside the click — the point
    body.classList.add("in-call");
    body.classList.remove("ended");
    history = []; ended = false; disposition = "qualifying"; note = "";
    $("log").textContent = ""; $("rows").textContent = "";
    $("sub").textContent = (direction === "inbound" ? "Incoming · " : "Outbound · ")
      + ({ "te-IN": "Telugu", "hi-IN": "Hindi", "en-IN": "English" }[lang])
      + (meta && meta.project ? " · " + meta.project : "");
    // The clock starts when the call CONNECTS — when her first line is ready —
    // not when the button was pressed. A timer that starts on the press counts
    // the connection attempt as call time, which is the one number on this
    // screen an investor might actually check against a phone bill.
    t0 = 0; $("timer").textContent = "00:00"; $("ttfa").textContent = "";
    // THE CALL TURNS THE MICROPHONE ON. There is no microphone button, because
    // there is no microphone button on a phone call — you answer it and you
    // talk. The Start click is the user gesture the browser needs for both the
    // audio unlock and the mic permission, so it is the right and only place.
    // PRESS AND HOLD TO TALK, by default.
    //
    // Hands-free needs the microphone open between her sentences, and on a
    // phone speaker — over Bluetooth especially, where the delay is outside the
    // browser's echo cancellation entirely — her voice comes back late enough
    // to look like yours. Every defence against that is a heuristic, I have
    // shipped three, and you have watched all three fail.
    //
    // While a finger is on the button the microphone is open and she is muted.
    // There is no window in which her audio can reach the recogniser, so the
    // loop is not unlikely, it is impossible. Hands-free stays available for
    // when the guards have been proven on real hardware rather than in a test.
    startMic();
    state(direction === "inbound" ? "answering…" : "connecting…");
    turn(null);                                // she opens
  }

  function hangup() {
    ended = true;
    if (utterance) utterance.cancelled = true;
    stopMic();
    clearInterval(tick); tick = null;
    try { element().pause(); } catch (e) {}
    body.classList.add("ended");
    element().muted = false;
    state("call ended");
    summarize();
  }

  // The score is computed SERVER-side from the flow's weights — a number the
  // model invented would not be reproducible, and a sales team that sees the
  // same call score differently twice stops believing all of them.
  function summarize() {
    var rows = $("rows");
    rows.textContent = "";
    row(rows, "Disposition", disposition);
    row(rows, "Turns", String(history.length));
    row(rows, "Duration", $("timer").textContent);
    row(rows, "Language", lang);
    row(rows, "Direction", direction);

    fetch("/api/anaga/summary", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ history: history })
    }).then(function (r) { return r.ok ? r.json() : null; }).then(function (d) {
      if (!d) return;
      if (typeof d.score === "number") $("score").textContent = String(d.score);
      if (d.band || d.disposition) $("band").textContent = d.band || d.disposition;
      if (d.summary) row(rows, "Summary", d.summary);
      if (d.nextAction) row(rows, "Next action", d.nextAction);
    }).catch(function () { /* the call record above still stands */ });
  }
  function row(into, k, v) {
    var d = document.createElement("div");
    var a = document.createElement("span"); a.textContent = k;
    var b = document.createElement("span"); b.textContent = v;
    d.appendChild(a); d.appendChild(b); into.appendChild(d);
  }

  /* ---------------- wiring ---------------- */
  function seg(id, attr, set) {
    $(id).addEventListener("click", function (ev) {
      var b = ev.target.closest("button");
      if (!b) return;
      Array.prototype.forEach.call(this.querySelectorAll("button"), function (x) {
        x.setAttribute("aria-pressed", String(x === b));
      });
      set(b.dataset[attr]);
    });
  }
  seg("dir", "dir", function (v) { direction = v; armOpening(); });
  seg("lang", "lang", function (v) { lang = v; armOpening(); });

  $("start").addEventListener("click", begin);
  $("again").addEventListener("click", function () {
    body.classList.remove("in-call", "ended");
    $("timer").textContent = "00:00"; $("score").textContent = "—"; $("band").textContent = "";
    state("");
  });
  $("end").addEventListener("click", hangup);
  $("compose").addEventListener("submit", function (ev) {
    ev.preventDefault();
    var t = $("say").value.trim();
    if (!t || thinking || ended) return;
    unlock();
    $("say").value = "";
    turn(t);
  });

