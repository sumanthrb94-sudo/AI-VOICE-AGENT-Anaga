  function fallback() {
    var n = history.filter(function (t) { return t.role === "agent"; }).length;
    var f = FALLBACK[lang] || FALLBACK["en-IN"];
    return f[Math.min(n, f.length - 1)];
  }

  var disposition = "qualifying";
  function reply(text, isEnd, disp, prerendered) {
    thinking = false;
    disposition = disp || disposition;
    history.push({ role: "agent", text: text });
    bubble("agent", text);                  // written first, spoken second
    if (!t0) { t0 = Date.now(); clock(); tick = setInterval(clock, 1000); }
    if (isEnd) ended = true;
    speak(text, prerendered).then(function () {
      speaking = false; body.classList.remove("speaking");
      if (ended) return hangup();
      state("");
    });
  }


  /* ---------------- first phrase first ----------------
     Synthesizing a whole line before playing any of it means the prospect
     waits for the LAST word to be rendered before hearing the FIRST. Bulbul
     takes ~3.3s on a two-sentence turn, and that is 3.3s of the agent
     visibly not answering.

     Split at phrase boundaries and the wait becomes the render time of the
     first phrase only; everything behind it renders while the earlier audio
     is still playing. The call leg has done this for a while
     (caller-agent/src/media/transport.js say()); the browser demo was still
     sending whole lines.

     Scanned by hand rather than split by regex ON PURPOSE. The obvious
     pattern is /(?<=[.!?।॥])\s+/, and lookbehind throws a SyntaxError at
     PARSE time on Safari before 16.4 — which would not degrade this page, it
     would blank it, on somebody's iPhone, in the room. */
  var SENTENCE_ENDS = ".!?\u0964\u0965";      // includes the Devanagari danda
  var CLAUSE_ENDS = ",;:\u2014\u2013";

  function splitOn(text, marks) {
    var out = [], cur = "";
    for (var i = 0; i < text.length; i++) {
      cur += text[i];
      if (marks.indexOf(text[i]) !== -1) {
        // A BOUNDARY NEEDS WHITESPACE AFTER IT, exactly as the server's
        // /(?<=[.!?।॥])\s+/ requires. This loop used to split on the mark
        // alone, so the two implementations disagreed on every decimal — 5 of
        // 7 realistic lines diverged.
        //
        //   "Your budget is 3.5 crore, is that right?"
        //     server  -> ["Your budget is 3.5 crore,", "is that right?"]
        //     browser -> ["Your budget is 3.", "5 crore, is that right?"]
        //
        // That is not cosmetic. api/anaga/turn.js prerenders phrase 0 with the
        // SERVER splitter and ships the audio; the browser then splits the
        // same line its own way and speaks "everything after phrase 0"
        // according to a different boundary. The prospect hears the number
        // twice, or hears it cut in half — on an ordinary budget question,
        // which is the one turn where a wrong number matters most.
        var atEnd = i + 1 >= text.length;
        if (!atEnd && !/\s/.test(text[i + 1])) continue;   // "3.5" is one word
        while (i + 1 < text.length && /\s/.test(text[i + 1])) i++;
        if (cur.trim()) out.push(cur.trim());
        cur = "";
      }
    }
    if (cur.trim()) out.push(cur.trim());
    return out;
  }

  // MAX_CHARS bounds vendor latency, which really does scale with characters.
  //
  // "Too short to be worth its own round trip" does NOT. That is about how long
  // the fragment takes to SAY, and every cheap proxy for it is biased by
  // script:
  //   - CHARACTERS are Latin-biased. "नमस्ते, मैं अनगा हूँ।" is 21 characters
  //     and about a second and a half of speech; the same sentence in English
  //     is 33. A 24-character floor merged every Hindi sentence back into one
  //     blob and defeated first-phrase-first in the languages we sell in.
  //   - WORDS are biased the other way. Telugu is agglutinative:
  //     "ఇప్పుడు మాట్లాడవచ్చా?" is a whole question in two words, and a
  //     four-word floor swallowed it just as badly.
  // So a fragment is a runt only when it is short by BOTH measures — which is
  // "Yes." and "Theek hai.", and nothing that carries a clause.
  var MAX_CHARS = 140, MIN_WORDS = 4, MIN_CHARS = 16;
  // THE FIRST PHRASE IS NOT LIKE THE OTHERS — it is the only one with no
  // earlier audio to hide behind, so it IS the wait. Synthesis time tracks
  // length almost linearly (measured: 21 chars 908 ms, 53 chars 2.4 s, 114
  // chars 4.2 s), so phrase zero is cut at the first clause boundary rather
  // than the sentence boundary the rest use. Costs one extra round trip on the
  // one phrase where a round trip is worth paying.
  // MUST MATCH shared/speech-split.js: the server prerenders phrase zero and
  // this file synthesizes 1..n, so a disagreement repeats or drops a phrase.
  var HEAD_CHARS = 36, MIN_HEAD = 12;
  function words(s) { return s.split(/\s+/).filter(Boolean).length; }
  function isRunt(s) { return words(s) < MIN_WORDS && s.length < MIN_CHARS; }

  function splitHead(first) {
    if (first.length <= HEAD_CHARS) return [first];
    var head = "", rest = [];
    splitOn(first, CLAUSE_ENDS).forEach(function (c) {
      if (head.length >= MIN_HEAD) rest.push(c);
      else head = head ? head + " " + c : c;
    });
    // No clause boundary inside the budget — leave it whole rather than cut
    // mid-word, which Bulbul pronounces as two separate words.
    if (!rest.length || head.length < MIN_HEAD) return [first];
    return [head, rest.join(" ")];
  }

  function splitForSpeech(text) {
    var whole = String(text == null ? "" : text).trim();
    if (!whole) return [];
    if (isRunt(whole)) return [whole];

    var parts = [];
    splitOn(whole, SENTENCE_ENDS).forEach(function (sentence) {
      if (sentence.length <= MAX_CHARS) { parts.push(sentence); return; }
      // A long sentence still blocks first audio, so break it at clause
      // boundaries. A hard character split would cut mid-word, and Bulbul
      // pronounces the fragments as two separate words.
      var acc = "";
      splitOn(sentence, CLAUSE_ENDS).forEach(function (clause) {
        if (acc && (acc.length + clause.length + 1) > MAX_CHARS) { parts.push(acc); acc = clause; }
        else acc = acc ? acc + " " + clause : clause;
      });
      if (acc) parts.push(acc);
    });

    // Merge runts forward. "Yes." alone is a whole network round trip to
    // render two syllables, which costs more than it saves.
    var merged = [];
    parts.forEach(function (p) {
      if (merged.length && isRunt(merged[merged.length - 1])) {
        merged[merged.length - 1] += " " + p;
      } else merged.push(p);
    });
    if (merged.length > 1 && isRunt(merged[merged.length - 1])) {
      var tail = merged.pop();
      merged[merged.length - 1] += " " + tail;
    }
    if (!merged.length) return [whole];
    // LAST, so the runt merge cannot undo it — the merge exists to lengthen
    // fragments and would put the head straight back where it came from.
    return splitHead(merged[0]).concat(merged.slice(1));
  }
  // Exposed so the browser test can assert the split without reimplementing it.
  window.__splitForSpeech = splitForSpeech;

  var utterance = null;                  // the line currently being spoken

  function speak(text, prerendered) {
    var a = element();
    // ORDER MATTERS: raise the flag BEFORE closing the mic. aborting the
    // recogniser fires onend synchronously, and onend reopens it unless it can
    // see that Anaga has the floor — so setting `speaking` afterwards meant the
    // mic was closed and reopened in the same tick, and half-duplex existed
    // only on paper. She would have heard herself and answered herself.
    speaking = true; body.classList.add("speaking");
    // The microphone stays open and stays listening. It is not hearing her:
    // echo cancellation removed her before the analyser saw the signal.

    if (utterance) utterance.cancelled = true;     // supersede whatever was mid-line
    var me = { cancelled: false };
    utterance = me;

    var parts = splitForSpeech(text);
    if (!parts.length) return Promise.resolve();
    var t0 = performance.now(), started = false;

    function synth(part) {
      return fetch("/api/tts", {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ text: part, lang: lang })   // voice: server default
      }).then(function (r) {
        return r.json().then(function (d) { return { ok: r.ok, d: d }; });
      }).then(function (res) {
        if (!res.ok || !res.d || !res.d.audio) throw new Error((res.d && res.d.error) || "tts_failed");
        return "data:" + (res.d.mime || "audio/mpeg") + ";base64," + res.d.audio;
      });
    }

    function play(src) {
      return new Promise(function (done) {
        a.onended = function () { done(); };
        // A superseded clip fires error when its src is swapped. That is not a
        // fault, and reporting it as one is how a page reads as broken while
        // playing correctly.
        a.onerror = function () { done(); };
        a.src = src;
        Promise.resolve(a.play()).then(function () {
          if (started || me.cancelled) return;
          started = true;
          // TIME TO FIRST AUDIO, measured, on this device. The whole reason for
          // this rewrite, so it is shown rather than asserted.
          var ms = Math.round(performance.now() - t0);
          $("ttfa").textContent = ms + " ms to first word";
        }, function () {
          note = "tap to allow audio"; state(""); done();
        });
      });
    }

    // Render part 0 — unless it was rendered before the call even started, in
    // which case the first word costs a decode and nothing else.
    var inflight = prerendered ? Promise.resolve(prerendered) : synth(parts[0]);
    inflight.catch(function () {});

    function step(i, pending) {
      if (me.cancelled || i >= parts.length) return Promise.resolve();
      return pending.then(function (src) {
        if (me.cancelled) return;
        // Start the NEXT phrase BEFORE playing this one. That overlap is the
        // point; kicking it off afterwards would serialise synthesis behind
        // audio again and buy nothing.
        var ahead = (i + 1 < parts.length) ? synth(parts[i + 1]) : null;
        if (ahead) ahead.catch(function () {});
        return play(src).then(function () {
          return step(i + 1, ahead || Promise.resolve(null));
        });
      }, function () {
        // Part-way through, the line is truncated but the call is live. The
        // transcript already carries every word — it is written before any of
        // this runs — so a dead vendor costs the audio and nothing else.
        note = "voice unavailable — transcript still live";
        state("");
      });
    }

    return step(0, inflight);
  }

  /* THE ECHO GUARD IS GONE, and its absence is the point.

     There used to be three defences here — a 15-second window of what she had
     said, a content-overlap score, a timing hangover — because the Web Speech
     API handed us her own voice and something had to filter it out. All three
     shipped, all three failed on real hardware, and the last one failed over
     Bluetooth where the delay is outside the browser altogether.

     mic.js captures with echoCancellation, so her voice is subtracted at the
     source. There is nothing to filter, nothing to score and nothing to guess.
     shared/echo-guard.js still exists for the TELEPHONY leg, where the echo
     comes back over a phone line and the browser cannot help us. */

  /** Somebody is talking over her. Stop, now, mid-word. */
  function bargeIn() {
    if (!utterance || utterance.cancelled) return;
    utterance.cancelled = true;
    try { element().pause(); } catch (e) {}
    speaking = false; body.classList.remove("speaking");
    // What she actually SAID is what goes in the record. She was cut off, so
    // the line is marked rather than trimmed to a guessed word — we know the
    // audio stopped, not which word it stopped on.
    markCutOff();
    state("");
    // Nothing to reopen: the microphone never closed. Whatever you are saying
    // over her is already being recorded and will arrive as the next turn.
  }
  window.__bargeIn = bargeIn;          // test introspection

  function markCutOff() {
    var last = history[history.length - 1];
    if (!last || last.role !== "agent" || /…\[cut off\]$/.test(last.text)) return;
    last.text += " …[cut off]";
    var bubbles = $("log").querySelectorAll(".ln.her");
    var el2 = bubbles[bubbles.length - 1];
    if (el2) el2.lastChild.nodeValue += " …[cut off]";
  }

  /* ---------------- listening: ONE echo-cancelled stream ----------------

     web/assets/mic.js owns the microphone. It captures through getUserMedia
     with echoCancellation, so Anaga's voice is removed BEFORE anything here
     sees it — which is why there is no echo guard in this file any more, no
     timing window, and no threshold. The three heuristics that used to live
     here all failed on real hardware; none of them is needed once the audio is
     clean at the source.

     The same stream does two jobs: an analyser decides when you start and stop
     talking, and a recorder captures the utterance, which is POSTed to
     /api/anaga/turn and transcribed by Sarvam. */
  var mic = null, micWanted = false;

  function startMic() {
    if (mic || !global_createMic) return Promise.resolve(false);
    mic = global_createMic({
      onSpeechStart: function () {
        // You are talking. If she is, she stops — that is barge-in, and it
        // needs no threshold of its own: the endpointer already decided this
        // is speech, and her voice is not in this signal.
        if (speaking) bargeIn();
        state("వింటున్నాను…");
      },
      onUtterance: function (u) { sendAudio(u); },
      onError: function (code) {
        micWanted = false;
        note = code === "denied"
          ? "microphone blocked — allow it, or type below"
          : "no microphone available — type below";
        state("");
      }
    });
    micWanted = true;
    window.__mic = mic;            // test introspection
    return mic.open();
  }

  function stopMic() {
    micWanted = false;
    if (mic) mic.close();
    mic = null;
  }

  /** One request for the whole turn: audio in, transcript + reply + audio out. */
  function sendAudio(u) {
    if (ended || thinking) return;
    thinking = true;
    state("…");
    // BEFORE the request, not after it. The whole point is to fill the gap the
    // request is about to open, so this has to happen while the audio is still
    // being read off the blob.
    if (u.ms >= ACK_MIN_UTTERANCE_MS) acknowledge();
    var reader = new FileReader();
    reader.onloadend = function () {
      var b64 = String(reader.result || "").split(",")[1];
      if (!b64) { thinking = false; return; }
      fetch("/api/anaga/turn?voice=1", {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          history: history, lang: lang, direction: direction,
          // How long they actually spoke, as the endpointer measured it. The
          // server cannot infer this from the bytes — a compressed container's
          // size tracks loudness, not length.
          audio: b64, mime: u.mime, ms: u.ms
        })
      }).then(function (r) {
        return r.json().catch(function () { return null; })
          .then(function (d) { return { ok: r.ok, d: d }; });
      }).then(function (res) {
        thinking = false;
        var d = res.d;
        // NAME THE RIGHT COMPONENT. This said "brain unavailable" for every
        // failure including a rejected recording, so an STT problem sent an
        // afternoon into the LLM — which was answering perfectly the whole
        // time. The server already says which half failed; use it.
        if (!res.ok || !d) {
          note = (d && d.error === "stt_unavailable")
            ? "could not hear that — say it again"
            : "brain unavailable";
          state("");
          return;
        }
        // Nothing intelligible — a door, a cough, a passing bus. Say nothing.
        if (d.ignored || !d.heard) { state(""); return; }

        history.push({ role: "user", text: d.heard });
        bubble("user", d.heard);
        if (isOptOut(d.heard)) return reply(BYE[lang] || BYE["en-IN"], true, "opt-out");
        if (!d.say) { state(""); return; }

        note = "";
        var pre = d.speak && d.speak.audio
          ? "data:" + (d.speak.mime || "audio/mpeg") + ";base64," + d.speak.audio
          : null;
        reply(d.say, d.end === true, d.disposition, pre);
      }).catch(function () {
        thinking = false;
        note = "brain unavailable"; state("");
      });
    };
    reader.readAsDataURL(u.blob);
  }

  var global_createMic = window.createMic;

