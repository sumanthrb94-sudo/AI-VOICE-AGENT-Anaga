/* ===================================================================
   Vaak — Anaga on a live call. The screen an investor watches.

   It is deliberately a REAL call and not a scripted playback: every line is
   generated by /api/anaga/turn against the versioned flow, and spoken by
   /api/tts. A demo that plays a recording proves the recording works.

   FOUR RULES:

   1. NOTHING PLAYS UNTIL A TAP. "Start the call" is the gesture that unlocks
      audio. Browsers reject a play() that is not inside a user gesture, and a
      fresh Audio() built after an await is not unlocked — it is refused
      silently, which looks exactly like a broken agent.

   2. THE MICROPHONE IS CAPTURED WITH ECHO CANCELLATION (web/assets/mic.js) and
      transcribed server-side by Sarvam. The Web Speech API cannot do this: it
      handed us Anaga's own voice off the speaker, she answered herself, and
      three separate heuristics failed to tell her voice from a prospect's.
      Clean audio at the source beats filtering afterwards.

   3. THE OPT-OUT IS OURS, NOT THE MODEL'S. It ends the call in this client
      whatever the model returns. On a real call the number joins the
      suppression list before anything else happens (docs/COMPLIANCE.md).

   4. THE TRANSCRIPT IS WRITTEN BEFORE THE AUDIO PLAYS. If synthesis fails, or
      the phone is on silent, the record still exists.
   =================================================================== */
