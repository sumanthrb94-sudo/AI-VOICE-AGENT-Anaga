/* ===================================================================
   Vaak — Anaga on a live call. The screen an investor watches.

   It is deliberately a REAL call and not a scripted playback: every line is
   generated by /api/anaga/turn against the versioned flow, and spoken by
   /api/tts. A demo that plays a recording proves the recording works.

   FOUR RULES:

   1. NOTHING PLAYS UNTIL A TAP. "Start the call" is the gesture that unlocks
      audio. Browsers reject a play() that is not inside a user gesture, and a
      fresh Audio() built after an await is not unlocked — it is refused
      silently, which looks exactly like a broken agent.

   2. HALF-DUPLEX. The mic is closed while Anaga speaks. An open mic on a phone
      speaker hears her and answers her; that is not hypothetical.

   3. THE OPT-OUT IS OURS, NOT THE MODEL'S. It ends the call in this client
      whatever the model returns. On a real call the number joins the
      suppression list before anything else happens (docs/COMPLIANCE.md).

   4. THE TRANSCRIPT IS WRITTEN BEFORE THE AUDIO PLAYS. If synthesis fails, or
      the phone is on silent, the record still exists.
   =================================================================== */
(function () {
  "use strict";

  var $ = function (id) { return document.getElementById(id); };
  var body = document.body;

  var lang = "te-IN", direction = "outbound";
  var history = [], ended = false, thinking = false, speaking = false;
  var t0 = 0, tick = null, draft = null, meta = null;

  /* ---------------- audio: one element, unlocked once ---------------- */
  var el = null, unlocked = false;
  var SILENT = "data:audio/wav;base64,UklGRiUAAABXQVZFZm10IBAAAAABAAEAgD4AAAB9AAACABAAZGF0YQEAAAAA";
  function element() { if (!el) { el = new Audio(); el.preload = "auto"; } return el; }
  function unlock() {                       // MUST run inside the gesture
    var a = element();
    if (unlocked) return;
    try {
      a.muted = true; a.src = SILENT;
      var p = a.play();
      if (p && p.then) p.then(function () {
        try { a.pause(); a.currentTime = 0; } catch (e) {}
        a.muted = false; unlocked = true;
      }, function () { a.muted = false; });
      else { a.muted = false; unlocked = true; }
    } catch (e) { /* play() reports it properly below */ }
  }

  /* ---------------- level meter ----------------
     Driven by the real audio element through WebAudio, so the bars move
     because she is speaking. A CSS animation that runs regardless would be a
     prop, and a prop on a demo screen is the thing an investor later finds
     out about. If WebAudio is unavailable the bars simply stay flat. */
  var BARS = 9, bars = [], actx = null, analyser = null, freq = null;
  (function buildBars() {
    var wrap = $("level");
    for (var i = 0; i < BARS; i++) {
      var b = document.createElement("i");
      wrap.appendChild(b); bars.push(b);
    }
  })();
  function meter() {
    if (actx) return;
    try {
      var AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return;
      actx = new AC();
      var src = actx.createMediaElementSource(element());
      analyser = actx.createAnalyser();
      analyser.fftSize = 64;
      src.connect(analyser); analyser.connect(actx.destination);
      freq = new Uint8Array(analyser.frequencyBinCount);
      (function paint() {
        requestAnimationFrame(paint);
        if (!analyser) return;
        analyser.getByteFrequencyData(freq);
        for (var i = 0; i < BARS; i++) {
          var v = speaking ? freq[i + 1] / 255 : 0;
          bars[i].style.height = (3 + v * 19) + "px";
        }
      })();
    } catch (e) { actx = null; }        // a meter is not worth failing a call
  }

  /* ---------------- transcript ---------------- */
  function bubble(role, text, isDraft) {
    var d = document.createElement("div");
    d.className = "ln " + (role === "agent" ? "her" : "you") + (isDraft ? " draft" : "");
    var who = document.createElement("small");
    who.textContent = role === "agent" ? "Anaga" : "Prospect";
    d.appendChild(who);
    d.appendChild(document.createTextNode(text));   // never innerHTML: this is speech
    if (isDraft) d.setAttribute("aria-hidden", "true");
    var log = $("log");
    log.appendChild(d); log.scrollTop = log.scrollHeight;
    return d;
  }
  function setDraft(text) {
    if (!text) return clearDraft();
    if (!draft) draft = bubble("user", text, true);
    else { draft.lastChild.nodeValue = text; $("log").scrollTop = $("log").scrollHeight; }
  }
  function clearDraft() {
    if (draft && draft.parentNode) draft.parentNode.removeChild(draft);
    draft = null;
  }
  // A sticky reason, so a transient "thinking…" cannot wipe out "the voice
  // provider is down". The same bug bit the sampler page: the line explaining
  // WHY the demo was degraded was overwritten by the next status update, and a
  // degraded demo that cannot say it is degraded just looks broken.
  var note = "";
  function state(m) { $("state").textContent = m || note; }

  /* Opt-out is honoured HERE. The model does not get a vote on it. */
  var OPT_OUT = ["ఆసక్తి లేదు", "కాల్ చేయవద్దు", "కాల్ చేయకండి", "నాకు వద్దు",
    "रुचि नहीं", "मत करो", "कॉल मत", "फोन मत",
    "not interested", "do not call", "don't call", "dont call", "remove me",
    "stop calling", "unsubscribe"];
  function isOptOut(t) {
    var s = String(t).toLowerCase();
    for (var i = 0; i < OPT_OUT.length; i++) if (s.indexOf(OPT_OUT[i]) !== -1) return true;
    return false;
  }
  var BYE = {
    "te-IN": "సరే, అర్థమైంది. మిమ్మల్ని డు-నాట్-కాల్ జాబితాలో చేరుస్తాను. ధన్యవాదాలు.",
    "hi-IN": "Theek hai, samajh gayi. Main aapka number do-not-call list mein daal deti hoon. Dhanyavaad.",
    "en-IN": "Understood. I'll add your number to our do-not-call list right away. Sorry to disturb you."
  };

  /* ---------------- the conversation ---------------- */
  function turn(text) {
    if (ended) return;
    if (text) {
      clearDraft();
      history.push({ role: "user", text: text });
      bubble("user", text);
      if (isOptOut(text)) return reply(BYE[lang] || BYE["en-IN"], true, "opt-out");
    }

    thinking = true;
    state("thinking…");
    fetch("/api/anaga/turn", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ history: history, lang: lang, direction: direction })
    }).then(function (r) { return r.ok ? r.json() : null; })
      .then(function (d) {
        if (d && d.say) { note = ""; return reply(d.say, d.end === true, d.disposition); }
        note = "brain unavailable"; state("");
        reply(fallback(), false, "qualifying");
      })
      .catch(function () {
        note = "brain unavailable"; state("");
        reply(fallback(), false, "qualifying");
      });
  }

  // Only when the brain is down. Deliberately dumb — not a second agent to keep
  // in sync with the flow, just enough that the screen never goes dead.
  var FALLBACK = {
    "te-IN": ["మీరు ఉండటానికా, పెట్టుబడి కోసమా?", "మీ బడ్జెట్ ఎంత?", "ఎన్ని బెడ్‌రూమ్‌లు?", "సైట్ విజిట్ పెట్టుకుందామా?"],
    "hi-IN": ["Aap rehne ke liye dekh rahe hain ya investment ke liye?", "Aapka budget kitna hai?", "Kitne bedroom chahiye?", "Site visit rakh lein?"],
    "en-IN": ["Are you looking to live in it, or to invest?", "What budget are you working with?", "How many bedrooms?", "Shall we set up a site visit?"]
  };
  function fallback() {
    var n = history.filter(function (t) { return t.role === "agent"; }).length;
    var f = FALLBACK[lang] || FALLBACK["en-IN"];
    return f[Math.min(n, f.length - 1)];
  }

  var disposition = "qualifying";
  function reply(text, isEnd, disp) {
    thinking = false;
    disposition = disp || disposition;
    history.push({ role: "agent", text: text });
    bubble("agent", text);                  // written first, spoken second
    if (!t0) { t0 = Date.now(); clock(); tick = setInterval(clock, 1000); }
    if (isEnd) ended = true;
    speak(text).then(function () {
      speaking = false; body.classList.remove("speaking");
      if (ended) return hangup();
      state("");
      if (micWanted) listen();
    });
  }

  function speak(text) {
    var a = element();
    // ORDER MATTERS: raise the flag BEFORE closing the mic. aborting the
    // recogniser fires onend synchronously, and onend reopens it unless it can
    // see that Anaga has the floor — so setting `speaking` afterwards meant the
    // mic was closed and reopened in the same tick, and half-duplex existed
    // only on paper. She would have heard herself and answered herself.
    speaking = true; body.classList.add("speaking");
    pauseListening();
    return fetch("/api/tts", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text: text, lang: lang })   // voice: server default
    }).then(function (r) { return r.json().then(function (d) { return { ok: r.ok, d: d }; }); })
      .then(function (res) {
        if (!res.ok || !res.d || !res.d.audio) throw new Error((res.d && res.d.error) || "tts_failed");
        return new Promise(function (done) {
          a.onended = function () { done(); };
          a.onerror = function () { state("audio unavailable"); done(); };
          a.src = "data:" + (res.d.mime || "audio/mpeg") + ";base64," + res.d.audio;
          Promise.resolve(a.play()).then(function () { meter(); }, function () {
            state("tap to allow audio"); done();
          });
        });
      })
      .catch(function () {
        note = "voice unavailable — transcript still live";
        state("");
      });
  }

  /* ---------------- listening (half-duplex) ---------------- */
  var SR = window.SpeechRecognition || window.webkitSpeechRecognition;
  var recog = null, micWanted = false;

  function listen() {
    if (!SR || ended || recog) return;
    recog = new SR();
    recog.lang = lang;
    recog.interimResults = true;
    recog.continuous = false;
    recog.onresult = function (ev) {
      var interim = "", final = "";
      for (var i = ev.resultIndex; i < ev.results.length; i++) {
        var r = ev.results[i];
        if (r.isFinal) final += r[0].transcript; else interim += r[0].transcript;
      }
      if (final.trim()) turn(final.trim()); else setDraft(interim);
    };
    recog.onerror = function (ev) {
      if (ev.error === "not-allowed" || ev.error === "service-not-allowed") {
        micOff(); state("mic blocked — type instead");
      }
    };
    recog.onend = function () {
      recog = null; clearDraft();
      if (micWanted && !thinking && !speaking && !ended) listen();
    };
    try { recog.start(); state("listening…"); } catch (e) { recog = null; }
  }
  function pauseListening() { if (recog) { try { recog.abort(); } catch (e) {} recog = null; } }
  function micOff() {
    micWanted = false;
    $("mic").setAttribute("aria-pressed", "false");
    pauseListening(); clearDraft();
  }

  /* ---------------- call lifecycle ---------------- */
  function clock() {
    var s = Math.floor((Date.now() - t0) / 1000);
    $("timer").textContent = String(Math.floor(s / 60)).padStart(2, "0") + ":"
      + String(s % 60).padStart(2, "0");
  }

  function begin() {
    unlock();                                  // inside the click — the point
    body.classList.add("in-call");
    body.classList.remove("ended");
    history = []; ended = false; disposition = "qualifying"; note = "";
    $("log").textContent = ""; $("rows").textContent = "";
    $("sub").textContent = (direction === "inbound" ? "Incoming · " : "Outbound · ")
      + ({ "te-IN": "Telugu", "hi-IN": "Hindi", "en-IN": "English" }[lang])
      + (meta && meta.project ? " · " + meta.project : "");
    // The clock starts when the call CONNECTS — when her first line is ready —
    // not when the button was pressed. A timer that starts on the press counts
    // the connection attempt as call time, which is the one number on this
    // screen an investor might actually check against a phone bill.
    t0 = 0; $("timer").textContent = "00:00";
    state(direction === "inbound" ? "answering…" : "connecting…");
    turn(null);                                // she opens
  }

  function hangup() {
    ended = true;
    micOff();
    clearInterval(tick); tick = null;
    try { element().pause(); } catch (e) {}
    body.classList.add("ended");
    state("call ended");
    summarize();
  }

  // The score is computed SERVER-side from the flow's weights — a number the
  // model invented would not be reproducible, and a sales team that sees the
  // same call score differently twice stops believing all of them.
  function summarize() {
    var rows = $("rows");
    rows.textContent = "";
    row(rows, "Disposition", disposition);
    row(rows, "Turns", String(history.length));
    row(rows, "Duration", $("timer").textContent);
    row(rows, "Language", lang);
    row(rows, "Direction", direction);

    fetch("/api/anaga/summary", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ history: history })
    }).then(function (r) { return r.ok ? r.json() : null; }).then(function (d) {
      if (!d) return;
      if (typeof d.score === "number") $("score").textContent = String(d.score);
      if (d.band || d.disposition) $("band").textContent = d.band || d.disposition;
      if (d.summary) row(rows, "Summary", d.summary);
      if (d.nextAction) row(rows, "Next action", d.nextAction);
    }).catch(function () { /* the call record above still stands */ });
  }
  function row(into, k, v) {
    var d = document.createElement("div");
    var a = document.createElement("span"); a.textContent = k;
    var b = document.createElement("span"); b.textContent = v;
    d.appendChild(a); d.appendChild(b); into.appendChild(d);
  }

  /* ---------------- wiring ---------------- */
  function seg(id, attr, set) {
    $(id).addEventListener("click", function (ev) {
      var b = ev.target.closest("button");
      if (!b) return;
      Array.prototype.forEach.call(this.querySelectorAll("button"), function (x) {
        x.setAttribute("aria-pressed", String(x === b));
      });
      set(b.dataset[attr]);
    });
  }
  seg("dir", "dir", function (v) { direction = v; });
  seg("lang", "lang", function (v) { lang = v; });

  $("start").addEventListener("click", begin);
  $("again").addEventListener("click", function () {
    body.classList.remove("in-call", "ended");
    $("timer").textContent = "00:00"; $("score").textContent = "—"; $("band").textContent = "";
    state("");
  });
  $("end").addEventListener("click", hangup);
  $("mic").addEventListener("click", function () {
    unlock();
    if (micWanted) return micOff();
    if (!SR) return state("this browser has no speech recogniser — type instead");
    micWanted = true;
    this.setAttribute("aria-pressed", "true");
    listen();
  });
  $("compose").addEventListener("submit", function (ev) {
    ev.preventDefault();
    var t = $("say").value.trim();
    if (!t || thinking || ended) return;
    unlock();
    $("say").value = "";
    turn(t);
  });

  /* Say up front which voice and which flow this is actually running — a demo
     that cannot name its own provider is a demo nobody can check. */
  fetch("/api/tts").then(function (r) { return r.json(); }).then(function (d) {
    meta = { voice: d.voice, model: d.model };
    $("src").textContent = d.available
      ? "Voice: " + (d.voice || "default") + " · " + (d.model || "bulbul")
        + " · " + (d.ready || []).join(", ")
      : "No voice provider configured — the transcript will still run.";
  }).catch(function () { $("src").textContent = ""; });
})();
