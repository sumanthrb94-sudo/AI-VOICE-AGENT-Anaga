  // Bumped by hand on every change to this file. "Still the same" and "you are
  // running last week's bundle" look identical from a phone, and I have spent
  // two rounds unable to tell them apart.
  var BUILD = "2026-08-10.5-sarvam-stt";

  var $ = function (id) { return document.getElementById(id); };
  var body = document.body;

  var lang = "te-IN", direction = "outbound";
  var history = [], ended = false, thinking = false, speaking = false;
  var t0 = 0, tick = null, draft = null, meta = null;

  /* ---------------- audio: one element, unlocked once ---------------- */
  var el = null, unlocked = false;
  var SILENT = "data:audio/wav;base64,UklGRiUAAABXQVZFZm10IBAAAAABAAEAgD4AAAB9AAACABAAZGF0YQEAAAAA";
  function element() { if (!el) { el = new Audio(); el.preload = "auto"; } return el; }
  function ackElement() { if (!ackEl) { ackEl = new Audio(); ackEl.preload = "auto"; } return ackEl; }
  function unlock() {                       // MUST run inside the gesture
    if (unlocked) return;
    // BOTH elements. The backchannel plays on its own, and an element that was
    // not touched inside the gesture is refused silently later — which is
    // indistinguishable from a bug and is exactly how the first one broke.
    [element(), ackElement()].forEach(function (a) {
      try {
        a.muted = true; a.src = SILENT;
        var p = a.play();
        if (p && p.then) p.then(function () {
          try { a.pause(); a.currentTime = 0; } catch (e) {}
          a.muted = false;
        }, function () { a.muted = false; });
        else a.muted = false;
      } catch (e) { /* play() reports it properly below */ }
    });
    unlocked = true;
  }

  /* ---------------- level meter ----------------
     Driven by the real audio element through WebAudio, so the bars move
     because she is speaking. A CSS animation that runs regardless would be a
     prop, and a prop on a demo screen is the thing an investor later finds
     out about. If WebAudio is unavailable the bars simply stay flat. */
  var BARS = 9, bars = [], actx = null, analyser = null, freq = null;
  (function buildBars() {
    var wrap = $("level");
    for (var i = 0; i < BARS; i++) {
      var b = document.createElement("i");
      wrap.appendChild(b); bars.push(b);
    }
  })();
  function meter() {
    if (actx) return;
    try {
      var AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return;
      actx = new AC();
      var src = actx.createMediaElementSource(element());
      analyser = actx.createAnalyser();
      analyser.fftSize = 64;
      src.connect(analyser); analyser.connect(actx.destination);
      freq = new Uint8Array(analyser.frequencyBinCount);
      (function paint() {
        requestAnimationFrame(paint);
        if (!analyser) return;
        analyser.getByteFrequencyData(freq);
        for (var i = 0; i < BARS; i++) {
          var v = speaking ? freq[i + 1] / 255 : 0;
          bars[i].style.height = (3 + v * 19) + "px";
        }
      })();
    } catch (e) { actx = null; }        // a meter is not worth failing a call
  }

  /* ---------------- transcript ---------------- */
